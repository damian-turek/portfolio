import type { Metadata } from 'next'
import { Anton, DM_Sans, Space_Mono } from 'next/font/google'
import '@/styles/globals.css'
import { AppProvider } from '@/providers'
import { Footer } from '@/components/molecules/Footer'
import { getLayoutData } from '@/parsers/getLayoutData'
import { Header } from '@/components/molecules/Header'
import { CustomCursor } from '@/components/CustomCursor'
import { routing } from '@/i18n/routing'
import { hasLocale } from 'next-intl'
import { notFound } from 'next/navigation'

const dmSans = DM_Sans({
  weight: ['300', '400', '500', '600', '700'],
  variable: '--font-dm-sans',
  subsets: ['latin'],
})

const spaceMono = Space_Mono({
  weight: ['400', '700'],
  variable: '--font-space-mono',
  subsets: ['latin'],
})

const anton = Anton({
  weight: '400',
  variable: '--font-anton',
  subsets: ['latin'],
})

export const metadata: Metadata = {
  title: 'Create Next App',
  description: 'Generated by create next app',
}

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }))
}

export default async function RootLayout({
  children,
  params,
}: LayoutProps<'/[locale]'>) {
  const { locale } = await params
  if (!hasLocale(routing.locales, locale)) notFound()

  const { HEADER_DATA, FOOTER_DATA } = await getLayoutData()

  return (
    <html
      lang={locale}
      suppressHydrationWarning
      className={`${anton.variable} ${spaceMono.variable} ${dmSans.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <AppProvider>
          <CustomCursor />
          <Header {...HEADER_DATA} />
          {children}
          <Footer {...FOOTER_DATA} />
        </AppProvider>
      </body>
    </html>
  )
}
